/**
 * The theme dump of the capture suite (UX-P0.14; research §18, plan P0.14): under each of the six themes and in the
 * run's look, the resolved `--vscode-*` custom properties VS Code puts on the main-panel webview's root, the body's
 * theme classes and attributes, and the computed values of the `--nuiget-*` tokens of `tokens.css` on the body (where
 * the high-contrast block applies). The suite writes two files per theme and look into `themes/` at the screenshots
 * root: the theme file (`<slug>.css` classic, `<slug>.modern.css` Modern UI: the `--vscode-*` values the artboards
 * load) and the token record (`<slug>.tokens.css`, `<slug>.modern.tokens.css`: the computed tokens, a record for P1.1
 * and P0.25 that nothing links, so no artboard inherits the product's tokens; UX-P0.14 rulings). `docs/design/themes/`
 * is copied from the `ui` job's `ui-screenshots` artifact only, never edited by hand.
 *
 * Plain data and string scripts, like `measure.ts`: `src/test/lint` imports it without ExTester.
 */

export interface ThemeDump {
    /** `--vscode-*` name → value, from the root element's inline style. */
    vars: Record<string, string>;
    /** `--nuiget-*` name → computed value on the body; empty when the token resolves to nothing there. */
    tokens: Record<string, string>;
    bodyClass: string;
    themeKind: string | null;
    themeName: string | null;
    dpr: number;
}

/** Where and on what the dump was taken, for the file's header. */
export interface DumpProvenance {
    look: 'modern' | 'classic';
    vscode: string;
    platform: string;
    /** `GITHUB_RUN_ID`, or `local`. */
    run: string;
    /** The run's date, `YYYY-MM-DD`. */
    date: string;
}

/**
 * Runs in the webview with the token names as its argument: what VS Code exported onto the root and how the tokens
 * resolve under the current theme and look.
 */
export const DUMP_THEME = `
    const names = arguments[0];
    const style = document.documentElement.style;
    const vars = {};
    for (let i = 0; i < style.length; i++) {
        const name = style[i];
        if (name.startsWith('--vscode-')) { vars[name] = style.getPropertyValue(name).trim(); }
    }
    const computed = getComputedStyle(document.body);
    const tokens = {};
    for (const name of names) { tokens[name] = computed.getPropertyValue(name).trim(); }
    return {
        vars,
        tokens,
        bodyClass: document.body.className,
        themeKind: document.body.dataset.vscodeThemeKind ?? null,
        themeName: document.body.dataset.vscodeThemeName ?? null,
        dpr: window.devicePixelRatio,
    };
`;

/** The `--nuiget-*` names a stylesheet declares (`--nuiget-x: …`), sorted and unique; usages are not declarations. */
export function declaredTokens(css: string): string[] {
    const withoutComments = css.replace(/\/\*[\s\S]*?\*\//g, '');
    return [...new Set([...withoutComments.matchAll(/(--nuiget-[a-z0-9-]+)\s*:/g)].map(match => match[1]))].sort();
}

/** The theme file's name: `<slug>.css` for the classic look (the planning dumps' name), `<slug>.modern.css` for Modern UI. */
export const themeDumpFile = (slug: string, look: 'modern' | 'classic'): string => `${slug}${look === 'modern' ? '.modern' : ''}.css`;

/**
 * The token record's name: `<slug>.tokens.css` or `<slug>.modern.tokens.css`. A theme slug has no dot, so an artboard's
 * `themes/<theme>.css` link never resolves to a record.
 */
export const tokenDumpFile = (slug: string, look: 'modern' | 'classic'): string => `${slug}${look === 'modern' ? '.modern' : ''}.tokens.css`;

const block = (selector: string, values: Record<string, string>): string[] => [
    `${selector} {`,
    ...Object.keys(values).sort().map(name => `    ${name}: ${values[name]};`),
    '}',
];

const lookName = (provenance: DumpProvenance): string => (provenance.look === 'modern' ? 'Modern UI' : 'classic look');
const bodyLine = (dump: ThemeDump): string =>
    `/* body class: ${dump.bodyClass} | data-vscode-theme-kind: ${dump.themeKind ?? ''} | data-vscode-theme-name: ${dump.themeName ?? ''} */`;

/** The theme file: the planning dumps' two header comments and `:root` block of `--vscode-*` values, sorted by name. */
export function formatThemeDump(theme: string, dump: ThemeDump, provenance: DumpProvenance): string {
    return [
        `/* Resolved --vscode-* custom properties of the nUIget main-panel webview under the theme "${theme}" on VS Code ${provenance.vscode} (${lookName(provenance)}, ${provenance.platform}, DPR ${dump.dpr}). Generated by the capture suite's theme dump (UX-P0.14) in run ${provenance.run} on ${provenance.date}; regenerate with that step, never edit by hand. */`,
        bodyLine(dump),
        ...block(':root', dump.vars),
        '',
    ].join('\n');
}

/**
 * The token record: its own header, the body-class line, and the computed `--nuiget-*` tokens as a `body` block (where
 * they were read; nothing loads the file), sorted by name; an empty value is a token that resolves to nothing there.
 */
export function formatTokenDump(theme: string, dump: ThemeDump, provenance: DumpProvenance): string {
    return [
        `/* Computed --nuiget-* tokens of src/webview/shared/tokens.css on the body of the nUIget main-panel webview under the theme "${theme}" on VS Code ${provenance.vscode} (${lookName(provenance)}, ${provenance.platform}, DPR ${dump.dpr}). A record for P1.1 and P0.25, never linked by an artboard; generated by the capture suite's theme dump (UX-P0.14) in run ${provenance.run} on ${provenance.date}; regenerate with that step, never edit by hand. */`,
        bodyLine(dump),
        ...block('body', dump.tokens),
        '',
    ].join('\n');
}
