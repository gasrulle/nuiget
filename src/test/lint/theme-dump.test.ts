// @vitest-environment jsdom
import * as fs from 'fs';
import * as path from 'path';
import { afterEach, describe, expect, it } from 'vitest';
import { declaredTokens, DUMP_THEME, formatThemeDump, formatTokenDump, type ThemeDump, themeDumpFile, tokenDumpFile } from '../ui/v2/themeDump';

/**
 * UX-P0.14: the theme dump of the capture suite. The UI job proves it in Chromium (`[theme]` lines and the 24 files of
 * `themes/`: twelve theme files, twelve token records); this test holds the token names, the in-page script and both
 * formats on every push.
 */
const root = path.resolve(__dirname, '../../..');

describe('theme dump (UX-P0.14)', () => {
    afterEach(() => {
        document.documentElement.removeAttribute('style');
        document.head.innerHTML = '';
        document.body.className = '';
        delete document.body.dataset.vscodeThemeKind;
        delete document.body.dataset.vscodeThemeName;
    });

    it('takes the token names tokens.css declares, not the ones it only uses', () => {
        expect(declaredTokens(':root {\n  --nuiget-a: var(--vscode-x);\n  /* --nuiget-commented: 1px; */\n  --nuiget-b:2px;\n}\nbody.x { --nuiget-a: red; color: var(--nuiget-used); }'))
            .toEqual(['--nuiget-a', '--nuiget-b']);
        const names = declaredTokens(fs.readFileSync(path.join(root, 'src/webview/shared/tokens.css'), 'utf8'));
        expect(names.length).toBeGreaterThan(50);
        expect(names).toContain('--nuiget-color-bg');
        expect(names.every(name => /^--nuiget-[a-z0-9-]+$/.test(name))).toBe(true);
    });

    it('reads the exported --vscode-* properties of the root, the body attributes and the tokens on the body', () => {
        document.documentElement.setAttribute('style', '--vscode-foreground: #cccccc; --vscode-font-size: 13px; color: red;');
        document.body.className = 'vscode-dark vscode-reduce-motion';
        document.body.dataset.vscodeThemeKind = 'vscode-dark';
        document.body.dataset.vscodeThemeName = 'Dark Modern';
        const dump = new Function(DUMP_THEME).call(undefined, ['--nuiget-color-fg']) as ThemeDump;
        expect(dump.vars).toEqual({ '--vscode-foreground': '#cccccc', '--vscode-font-size': '13px' });
        expect(Object.keys(dump.tokens)).toEqual(['--nuiget-color-fg']);
        expect(dump.bodyClass).toBe('vscode-dark vscode-reduce-motion');
        expect(dump.themeKind).toBe('vscode-dark');
        expect(dump.themeName).toBe('Dark Modern');
        expect(typeof dump.dpr).toBe('number');
    });

    const dump: ThemeDump = {
        vars: { '--vscode-widget-border': '#313131', '--vscode-activityBar-background': '#181818', '--vscode-activityBarBadge-background': '#0078d4' },
        tokens: { '--nuiget-space-2': '4px', '--nuiget-color-bg': '#1f1f1f', '--nuiget-none': '' },
        bodyClass: 'vscode-dark vscode-reduce-motion', themeKind: 'vscode-dark', themeName: 'Dark Modern', dpr: 1,
    };
    const provenance = { look: 'classic' as const, vscode: '1.140.0', platform: 'linux', run: '123', date: '2026-10-24' };

    it('writes the theme file in the planning dumps\' shape: the header and a sorted :root block of --vscode-* values only', () => {
        const text = formatThemeDump('Dark Modern', dump, provenance);
        const lines = text.split('\n');
        expect(lines[0]).toBe('/* Resolved --vscode-* custom properties of the nUIget main-panel webview under the theme "Dark Modern" on VS Code 1.140.0 (classic look, linux, DPR 1). Generated by the capture suite\'s theme dump (UX-P0.14) in run 123 on 2026-10-24; regenerate with that step, never edit by hand. */');
        expect(lines[1]).toBe('/* body class: vscode-dark vscode-reduce-motion | data-vscode-theme-kind: vscode-dark | data-vscode-theme-name: Dark Modern */');
        expect(lines.slice(2)).toEqual([
            ':root {',
            '    --vscode-activityBar-background: #181818;',
            '    --vscode-activityBarBadge-background: #0078d4;',
            '    --vscode-widget-border: #313131;',
            '}',
            '',
        ]);
        // No artboard that links the theme file may inherit a product token (UX-P0.14 ruling).
        expect(text).not.toContain('--nuiget-');
    });

    it('writes the token record apart: its own header, the body-class line and a sorted body block of the computed tokens', () => {
        const lines = formatTokenDump('Dark Modern', dump, { ...provenance, look: 'modern' }).split('\n');
        expect(lines[0]).toBe('/* Computed --nuiget-* tokens of src/webview/shared/tokens.css on the body of the nUIget main-panel webview under the theme "Dark Modern" on VS Code 1.140.0 (Modern UI, linux, DPR 1). A record for P1.1 and P0.25, never linked by an artboard; generated by the capture suite\'s theme dump (UX-P0.14) in run 123 on 2026-10-24; regenerate with that step, never edit by hand. */');
        expect(lines[1]).toBe('/* body class: vscode-dark vscode-reduce-motion | data-vscode-theme-kind: vscode-dark | data-vscode-theme-name: Dark Modern */');
        expect(lines.slice(2)).toEqual(['body {', '    --nuiget-color-bg: #1f1f1f;', '    --nuiget-none: ;', '    --nuiget-space-2: 4px;', '}', '']);
    });

    it('names the classic dump as the planning dumps were named, the Modern UI dump beside it, and the token records apart', () => {
        expect(themeDumpFile('dark-modern', 'classic')).toBe('dark-modern.css');
        expect(themeDumpFile('dark-modern', 'modern')).toBe('dark-modern.modern.css');
        expect(tokenDumpFile('dark-modern', 'classic')).toBe('dark-modern.tokens.css');
        expect(tokenDumpFile('dark-modern', 'modern')).toBe('dark-modern.modern.tokens.css');
    });

    it('keeps the committed files in their shapes: theme files with a :root block and no token, token records with a body block', () => {
        const dir = path.join(root, 'docs/design/themes');
        for (const file of fs.readdirSync(dir).filter(name => name.endsWith('.css'))) {
            const text = fs.readFileSync(path.join(dir, file), 'utf8');
            // A Windows checkout ends the committed lines with CRLF.
            const lines = text.split(/\r?\n/);
            expect(lines[1], file).toMatch(/^\/\* body class: .* \| data-vscode-theme-kind: .* \| data-vscode-theme-name: .* \*\/$/);
            if (file.endsWith('.tokens.css')) {
                expect(lines[0], file).toMatch(/^\/\* Computed --nuiget-\* tokens of src\/webview\/shared\/tokens\.css on the body of the nUIget main-panel webview under the theme "[^"]+" on VS Code \d+\.\d+\.\d+ /);
                expect(lines[2], file).toBe('body {');
            } else {
                expect(lines[0], file).toMatch(/^\/\* Resolved --vscode-\* custom properties of the nUIget main-panel webview under the theme "[^"]+" on VS Code \d+\.\d+\.\d+ /);
                expect(lines[2], file).toBe(':root {');
                expect(text, file).not.toContain('--nuiget-');
            }
        }
    });
});
