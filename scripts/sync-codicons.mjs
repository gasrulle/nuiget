// Writes the icon module of the webviews from the pinned codicon release (UX-P1.4a, ADR-012, D27, DS-ICON-1, DS-ICON-5):
//   node scripts/sync-codicons.mjs --write
//   node scripts/sync-codicons.mjs --check
// writes the module, or checks the list against the release and that the module equals the generation byte for byte. `docs/design/icons.json` is the list (export name → codicon file), `@vscode/codicons` the
// exact-pinned drawings. An SVG with anything but `<path>` elements is refused by name, never drawn with a part missing:
// the item that needs such a glyph decides.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const LIST = path.join(ROOT, 'docs/design/icons.json');
export const MODULE = path.join(ROOT, 'src/webview/shared/primitives/icons.tsx');
const RELEASE_DIR = path.join(ROOT, 'node_modules/@vscode/codicons');

/** The first line of a generated module, and what tells it from the hand-drawn one. */
export const GENERATED_MARK = '/* @generated by scripts/sync-codicons.mjs';

const PATH_ATTRIBUTES = new Set(['d', 'fill-rule', 'clip-rule']);
const ROOT_ATTRIBUTES = new Set(['width', 'height', 'viewBox', 'xmlns', 'fill']);

const ATTRIBUTE = /([^\s=]+)=(?:"([^"]*)"|'([^']*)')/g;
const attributesOf = text => Object.fromEntries([...text.matchAll(ATTRIBUTE)].map(match => [match[1], match[2] ?? match[3]]));

/** The `viewBox` and paths of a codicon SVG, or a throw that names what the generator cannot keep verbatim. */
export function parseSvg(name, svg) {
    // Every opening tag, whatever its attributes look like: what the attribute reader cannot read is refused, never skipped.
    const elements = [...svg.matchAll(/<([a-zA-Z][^\s/>]*)([^>]*)>/g)];
    for (const [, tag, text] of elements) {
        if (text.replace(ATTRIBUTE, '').replace('/', '').trim() !== '') {
            throw new Error(`${name}: <${tag}> has an attribute the generator cannot read`);
        }
    }
    const [root, ...rest] = elements;
    if (root === undefined || root[1] !== 'svg') {
        throw new Error(`${name}: no <svg> root`);
    }
    const rootAttributes = attributesOf(root[2]);
    const foreign = Object.keys(rootAttributes).filter(key => !ROOT_ATTRIBUTES.has(key));
    if (foreign.length > 0) {
        throw new Error(`${name}: <svg> attribute ${foreign.join(', ')} is not kept by the generator`);
    }
    if (rootAttributes.viewBox === undefined) {
        throw new Error(`${name}: no viewBox`);
    }
    const paths = rest.map(([, tag, text]) => {
        if (tag !== 'path') {
            throw new Error(`${name}: <${tag}> is not a path`);
        }
        const attributes = attributesOf(text);
        const other = Object.keys(attributes).filter(key => !PATH_ATTRIBUTES.has(key));
        if (other.length > 0) {
            throw new Error(`${name}: <path> attribute ${other.join(', ')} is not kept by the generator`);
        }
        if (attributes.d === undefined) {
            throw new Error(`${name}: <path> without d`);
        }
        return attributes;
    });
    if (paths.length === 0) {
        throw new Error(`${name}: no <path>`);
    }
    return { viewBox: rootAttributes.viewBox, paths };
}

/** The installed release's SVG of a codicon file; a throw when the release has none. */
export function readCodicon(file, releaseDir = RELEASE_DIR) {
    const svg = path.join(releaseDir, 'src/icons', `${file}.svg`);
    if (!existsSync(svg)) {
        throw new Error(`${file}: not in the installed @vscode/codicons`);
    }
    return parseSvg(file, readFileSync(svg, 'utf8'));
}

const pathElement = ({ d, 'fill-rule': fillRule, 'clip-rule': clipRule }) =>
    `<path${fillRule ? ` fillRule="${fillRule}"` : ''}${clipRule ? ` clipRule="${clipRule}"` : ''} d="${d}" />`;

/** The whole icon module for a list, the release's drawings read through `read`. */
export function generateModule(list, read = readCodicon) {
    const icons = Object.entries(list.icons).map(([name, file]) => {
        const { viewBox, paths } = read(file);
        return [
            `/** Codicon: ${file} */`,
            `export const ${name} = /* @__PURE__ */ React.memo<IconProps>(({ size = defaultSize, className, title }) => (`,
            `    <svg width={size} height={size} viewBox="${viewBox}" fill="currentColor" data-codicon="${file}" className={className} aria-hidden={title ? undefined : true} role={title ? 'img' : undefined}>`,
            '        {title && <title>{title}</title>}',
            ...paths.map(entry => `        ${pathElement(entry)}`),
            '    </svg>',
            '));',
            '',
        ].join('\n');
    });
    return [
        `${GENERATED_MARK} from @vscode/codicons ${list.release}; do not edit. Code MIT; drawings CC-BY-4.0 (https://github.com/microsoft/vscode-codicons, LICENSE) */`,
        '/**',
        ' * Inline SVG icons: a webview has no codicon font of its own (ADR-012). All use `currentColor`, so a class colours them.',
        ' * An icon takes a size, a class and a title, and nothing that would render an inline declaration: the Content Security',
        ' * Policy of the webviews admits none (ADR-006). Without a title an icon is decoration and hidden from assistive',
        ' * technology; with one it is an image with that accessible name.',
        ' */',
        "import React from 'react';",
        '',
        'export interface IconProps {',
        '    /** Width and height in CSS pixels; the default is the icon size of a row (`--nuiget-icon-size-md`). */',
        '    size?: number;',
        '    className?: string;',
        '    /** Accessible name. An icon that only repeats the text next to it has none. */',
        '    title?: string;',
        '}',
        '',
        'const defaultSize = 16;',
        '',
        ...icons,
    ].join('\n');
}

export function readList() {
    return JSON.parse(readFileSync(LIST, 'utf8'));
}

const installedRelease = () => JSON.parse(readFileSync(path.join(RELEASE_DIR, 'package.json'), 'utf8')).version;

/** Writes the module of a list to `target`, line ends LF. */
export function write({ list = readList(), target = MODULE, read = readCodicon } = {}) {
    writeFileSync(target, generateModule(list, read));
}

/** The lines `--check` prints; a throw is a failed check. */
export function check({ list = readList(), installed = installedRelease(), module: moduleText = readFileSync(MODULE, 'utf8'), read = readCodicon } = {}) {
    if (installed !== list.release) {
        throw new Error(`docs/design/icons.json names ${list.release}, the installed release is ${installed}`);
    }
    const generated = generateModule(list, read);
    const current = moduleText.replace(/\r\n/g, '\n');
    const count = Object.keys(list.icons).length;
    if (!current.startsWith(GENERATED_MARK)) {
        throw new Error('src/webview/shared/primitives/icons.tsx does not carry the generator\'s header: run the script');
    }
    if (current !== generated) {
        throw new Error('src/webview/shared/primitives/icons.tsx differs from the generation: run the script, never edit the file');
    }
    return [`${count} icons match @vscode/codicons ${installed}`];
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const writing = process.argv.includes('--write');
    if (!writing && !process.argv.includes('--check')) {
        console.error('usage: node scripts/sync-codicons.mjs --write | --check');
        process.exit(2);
    }
    try {
        if (writing) {
            write();
        }
        for (const line of check()) {
            console.log(line);
        }
    } catch (error) {
        console.error(`sync-codicons: ${error.message}`);
        process.exit(1);
    }
}
